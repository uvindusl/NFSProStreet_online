#!/usr/bin/env python3
"""Lift the guest's SEH filters, handlers and establisher thunk.

The Windows exception dispatcher has to *call* guest code at addresses the
lifter never saw as function entries: the filter expressions and the handlers
that the game parks in its __except scope tables, and the MSVCR80 thunk that
establishes the frame.  They live in the middle of other functions, so the
analysis phase does not make them entries and out/lift-boot has no code for
them.

This script lifts exactly those addresses on their own and writes
lifter/runtime/seh_lifted.c, a small translation unit the runtime links in and
registers in the dispatch table.

Whether the boot lift already defines one of these addresses depends on the
seeds: scripts/boot_seeds.py seeds every .rdata/.data word that points into
.text, and the scope tables live in .data, so their filter/handler addresses
are lift entries as soon as .data is scanned.  The lift's out/lift-boot/decls.h
is therefore read here and any address it already declares is skipped -- lifting
it again would be a duplicate symbol at link time.

Usage: scripts/lift_seh.py
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lifter" / "tools"))

from lift import Lifter  # noqa: E402

EXE = ROOT / "artifacts" / "nfs.exe.unpacked"
OUT = ROOT / "lifter" / "runtime" / "seh_lifted.c"
GEN = Path(os.environ.get("GEN", ROOT / "out" / "lift-boot"))

# address -> what it is
ENTRIES = [
    # the MSVCR80!_except_handler3 thunk the game installs as its establisher
    (0x009204D8, "thunk: jmp [IAT _except_handler3]"),
    # sub_00905610 (render thread) scope table 0xa42df8
    (0x009056BE, "filter: sub_00905610, CONTINUE_EXECUTION"),
    (0x009056C2, "handler: sub_00905610"),
    # sub_009058d0 scope table 0xa42e08
    (0x00905982, "filter: sub_009058d0, CONTINUE_EXECUTION"),
    (0x00905986, "handler: sub_009058d0"),
    # sub_00904ec0 (set thread name) scope table 0xa42de8
    (0x00904F3E, "filter: sub_00904ec0, CONTINUE_EXECUTION"),
    (0x00904F42, "handler: sub_00904ec0"),
    # sub_008ebfd0 scope table 0xa42dd0
    (0x008EC014, "filter: sub_008ebfd0, catch all"),
    (0x008EC01A, "handler: sub_008ebfd0"),
    # sub_008ebfd0 second scope table 0xa42de0
    (0x008EC057, "filter: sub_008ebfd0, second __except"),
    (0x008EC05D, "handler: sub_008ebfd0, second __except"),
    # sub_0091c4a0 scope table 0xa42e18
    (0x0091C540, "filter: sub_0091c4a0"),
    (0x0091C550, "handler: sub_0091c4a0"),
]


def _already_lifted():
    """addresses out/lift-boot already provides as sub_XXXXXXXX -> where"""
    have = {}
    decls = GEN / "decls.h"
    if decls.exists():
        for m in re.findall(r"void sub_([0-9a-f]{8})\(CPU\*\);", decls.read_text()):
            have[int(m, 16)] = "decls.h"
    stubs = GEN / "stubs.c"
    if stubs.exists():
        for m in re.findall(r"void sub_([0-9a-f]{8})\(CPU \*c\)", stubs.read_text()):
            have[int(m, 16)] = "stubs.c"
    return have


def main():
    # Anything the boot lift already defines must not be defined here as well.
    have = _already_lifted()
    entries = []
    for a, why in ENTRIES:
        where = have.get(a)
        if where == "decls.h":
            print(f"  skip 0x{a:08x}: already lifted by out/lift-boot ({why})")
            continue
        if where == "stubs.c":
            # A trapping stub is not usable as an exception filter/handler, but
            # defining it here would collide with stubs.c.  Surface it loudly.
            print(f"  WARN 0x{a:08x}: lift produced only a stub; SEH will trap")
        entries.append((a, why))
    if not entries:
        print("  nothing to lift: out/lift-boot already defines every entry")

    L = Lifter(str(EXE), comments=False, trap=True)
    parts = []
    addrs = []
    ptrs = []
    for a, why in entries:
        code, _tg = L.lift(a)
        if f"sub_{a:08x}" not in code:
            raise SystemExit(f"lift of 0x{a:08x} produced no sub_{a:08x}")
        parts.append(f"/* {why} */\n{code}")
        addrs.append(a)
        ptrs.append(f"sub_{a:08x}")

    with OUT.open("w") as f:
        f.write("/* Generated by scripts/lift_seh.py -- do not edit.\n"
                " *\n"
                " * The Windows exception dispatcher calls guest code at addresses\n"
                " * that are not function entries: the __except filter expressions and\n"
                " * handlers the game keeps in its scope tables, and the MSVCR80\n"
                " * _except_handler3 thunk.  They are lifted here on their own and\n"
                " * registered in the dispatch table by dispatch_init(). */\n"
                "#include \"cpu.h\"\n"
                "#include \"decls.h\"\n\n")
        f.write("\n".join(parts))
        f.write("\n\nconst uint32_t g_seh_fn_addr[] = {\n")
        for a in addrs:
            f.write(f"  0x{a:08x}u,\n")
        f.write("};\n")
        f.write("const guest_fn_t g_seh_fn_ptr[] = {\n")
        for p in ptrs:
            f.write(f"  {p},\n")
        f.write("};\n")
        f.write(f"const uint32_t g_seh_fn_count = {len(addrs)};\n")
    print(f"-> {OUT.relative_to(ROOT)} ({len(addrs)} entries)")


if __name__ == "__main__":
    main()
